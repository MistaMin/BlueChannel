// Derives the panel-value <-> component-value tables from the stage netlists (analogue response), and
// writes Source/Model/Calibration.h. Panel legends (dB, Hz) are mapped to pot positions by measuring the
// transcribed circuit, so a knob reading is what the circuit does at that setting.
//
// Usage: BlueChannelCalibrate > Source/Model/Calibration.h

#include "Circuit/DkStage.h"
#include "Circuit/Netlists.h"

#include <cmath>
#include <cstdio>
#include <functional>
#include <string>
#include <vector>

using namespace bluechannel::circuit;

static double dbAt(DkStage& s, double f, int out = 0)
{
    return 20.0 * std::log10(std::abs(s.analogResponse(out, 0, f)) + 1e-30);
}

// Frequency of the largest |dB - ref| deviation on a log grid.
static double peakFreq(DkStage& s, double f0, double f1, double* peakDb = nullptr, bool dip = false)
{
    double best = dip ? 1e9 : -1e9, bf = f0;
    for (int i = 0; i <= 400; ++i)
    {
        const double f = f0 * std::pow(f1 / f0, i / 400.0);
        const double d = dbAt(s, f);
        if (dip ? d < best : d > best) { best = d; bf = f; }
    }
    // refine
    for (int it = 0; it < 30; ++it)
    {
        const double fa = bf / std::pow(f1 / f0, 1.0 / 800.0), fb = bf * std::pow(f1 / f0, 1.0 / 800.0);
        const double da = dbAt(s, fa), db = dbAt(s, fb);
        if (dip ? da < best : da > best) { best = da; bf = fa; }
        else if (dip ? db < best : db > best) { best = db; bf = fb; }
        else break;
    }
    if (peakDb) *peakDb = best;
    return bf;
}

// -3 dB point (relative to the passband value `ref`) by bisection in log frequency.
static double cornerFreq(DkStage& s, double fLo, double fHi, double ref, bool lowpass)
{
    for (int it = 0; it < 60; ++it)
    {
        const double fm = std::sqrt(fLo * fHi);
        const bool above = dbAt(s, fm) > ref - 3.0103;
        if (lowpass == above) fLo = fm; else fHi = fm;
    }
    return std::sqrt(fLo * fHi);
}

static void table(const char* name, const std::vector<double>& v)
{
    std::printf("inline constexpr double %s[%zu] = {", name, v.size());
    for (size_t i = 0; i < v.size(); ++i) std::printf("%s%.6g", i == 0 ? "\n    " : i % 8 ? ", " : ",\n    ", v[i]);
    std::printf(" };\n");
}

int main()
{
    using namespace netlists;
    std::printf("// SPDX-License-Identifier: MIT\n// Copyright (c) 2026 OpenGrid\n#pragma once\n\n");
    std::printf("// Generated by tests/calibrate.cpp from the stage netlists. Do not edit by hand.\n");
    std::printf("// Each table samples one control at kPotSteps evenly spaced pot positions (0..1).\n\n");
    std::printf("namespace bluechannel::model::calibration\n{\n");
    const int steps = 65;
    std::printf("inline constexpr int kPotSteps = %d;\n\n", steps);
    auto pos = [&](int i) { return double(i) / double(steps - 1); };

    // Trim and make-up gain (dB at 1 kHz) versus pot fraction.
    {
        DkStage s(kTrim);
        std::vector<double> v;
        for (int i = 0; i < steps; ++i) { s.setParam(s.param("trim"), pos(i)); v.push_back(dbAt(s, 1000.0)); }
        table("kTrimDb", v);
        DkStage m(kMakeup);
        v.clear();
        for (int i = 0; i < steps; ++i) { m.setParam(m.param("makeup"), pos(i)); v.push_back(dbAt(m, 1000.0)); }
        table("kMakeupDb", v);
        DkStage f(kFader);
        v.clear();
        for (int i = 0; i < steps; ++i) { f.setParam(f.param("fader"), std::pow(pos(i), 3.0)); v.push_back(dbAt(f, 1000.0)); }
        std::printf("// Fader table uses track fraction = position^3 for resolution at low levels.\n");
        table("kFaderDb", v);
    }

    // Filter corners: every corner scales as 1 / (R + 620), so one constant per filter is enough.
    {
        DkStage s(kFilters);
        s.setParam(s.param("hpr"), 47000);
        s.setParam(s.param("lpr"), 4700);
        const double fl = cornerFreq(s, 1000.0, 200000.0, dbAt(s, 300.0), true);
        s.setParam(s.param("lpr"), 0.001);
        s.setParam(s.param("hpr"), 4700);
        const double fh = cornerFreq(s, 5.0, 5000.0, dbAt(s, 3000.0), false);
        std::printf("\n// -3 dB corner (Hz) = constant / (pot ohms + 620)\n");
        std::printf("inline constexpr double kLowPassConstant = %.6g;\n", fl * (4700 + 620));
        std::printf("inline constexpr double kHighPassConstant = %.6g;\n\n", fh * (4700 + 620));
    }

    // Shelves: gain at the shelf extreme versus pot, measured at position 3 (LF 160 Hz, HF 10 kHz).
    {
        DkStage s(kShelves);
        s.setParam(s.param("lfsel"), 3);
        s.setParam(s.param("hfsel"), 3);
        s.setParam(s.param("hfgain"), 0.5);
        std::vector<double> v;
        for (int i = 0; i < steps; ++i) { s.setParam(s.param("lfgain"), pos(i)); v.push_back(dbAt(s, 10.0)); }
        table("kLowShelfDb", v);
        s.setParam(s.param("lfgain"), 0.5);
        v.clear();
        for (int i = 0; i < steps; ++i) { s.setParam(s.param("hfgain"), pos(i)); v.push_back(dbAt(s, 40000.0)); }
        table("kHighShelfDb", v);
        // Corner (half-gain point in dB) for each switch position at full boost, for the legends.
        std::vector<double> lf, hf;
        for (int k = 0; k < 8; ++k)
        {
            s.setParam(s.param("lfsel"), k); s.setParam(s.param("hfsel"), k);
            s.setParam(s.param("lfgain"), 0.0); s.setParam(s.param("hfgain"), 0.5);
            const double full = dbAt(s, 2.0);
            double lo = 2.0, hi = 20000.0;
            for (int it = 0; it < 60; ++it) { const double m = std::sqrt(lo * hi); (dbAt(s, m) > full * 0.5 ? lo : hi) = m; }
            lf.push_back(std::sqrt(lo * hi));
            s.setParam(s.param("lfgain"), 0.5); s.setParam(s.param("hfgain"), 0.0);
            const double fullh = dbAt(s, 90000.0);
            lo = 20.0; hi = 90000.0;
            for (int it = 0; it < 60; ++it) { const double m = std::sqrt(lo * hi); (dbAt(s, m) > fullh * 0.5 ? hi : lo) = m; }
            hf.push_back(std::sqrt(lo * hi));
        }
        std::printf("// Half-boost frequency of each shelf switch position (diagnostic, not a legend).\n");
        table("kLowShelfHalfHz", lf);
        table("kHighShelfHalfHz", hf);
    }

    // Parametric bands: centre frequency versus frequency pot (both ranges), peak boost versus gain pot,
    // and the -3 dB bandwidth Q at full boost versus Q pot.
    for (int band = 0; band < 2; ++band)
    {
        DkStage s(band == 0 ? kLmf : kHmf);
        const char* nm = band == 0 ? "Lmf" : "Hmf";
        const double f0 = band == 0 ? 5.0 : 50.0, f1 = band == 0 ? 20000.0 : 90000.0;
        s.setParam(s.param("q"), 0.5);
        for (int x3 = 0; x3 < 2; ++x3)
        {
            s.setParam(s.param("x3"), x3);
            std::vector<double> v;
            for (int i = 0; i < steps; ++i)
            {
                s.setParam(s.param("freq"), pos(i));
                s.setParam(s.param("gain"), 0.0);   // check polarity below; 0 = one extreme
                double pk;
                const double fb = peakFreq(s, f0, f1, &pk);
                s.setParam(s.param("gain"), 1.0);
                double dp;
                const double fd = peakFreq(s, f0, f1, &dp, true);
                v.push_back(std::abs(pk) > std::abs(dp) ? fb : fd);
            }
            table((std::string("k") + nm + (x3 ? "FreqX3Hz" : "FreqHz")).c_str(), v);
        }
        s.setParam(s.param("x3"), 0);
        s.setParam(s.param("freq"), 0.5);
        s.setParam(s.param("q"), 0.5);
        // Boost side: the extreme with the larger positive peak.
        s.setParam(s.param("gain"), 0.0);
        double pk0; const double fc0 = peakFreq(s, f0, f1, &pk0);
        s.setParam(s.param("gain"), 1.0);
        double pk1; const double fc1 = peakFreq(s, f0, f1, &pk1);
        const double boostPos = pk0 > pk1 ? 0.0 : 1.0;
        const double fc = pk0 > pk1 ? fc0 : fc1;
        std::printf("inline constexpr double k%sBoostPosition = %g;\n", nm, boostPos);
        std::vector<double> g;
        for (int i = 0; i < steps; ++i) { s.setParam(s.param("gain"), pos(i)); g.push_back(dbAt(s, fc)); }
        table((std::string("k") + nm + "GainDb").c_str(), g);
        std::vector<double> q;
        s.setParam(s.param("gain"), boostPos);
        for (int i = 0; i < steps; ++i)
        {
            s.setParam(s.param("q"), pos(i));
            double pk;
            const double fp = peakFreq(s, f0, f1, &pk);
            const double edge = pk - 3.0103;
            double lo = fp / 50.0, hi = fp;
            for (int it = 0; it < 60; ++it) { const double m = std::sqrt(lo * hi); (dbAt(s, m) > edge ? hi : lo) = m; }
            const double fl = std::sqrt(lo * hi);
            lo = fp; hi = fp * 50.0;
            for (int it = 0; it < 60; ++it) { const double m = std::sqrt(lo * hi); (dbAt(s, m) > edge ? lo : hi) = m; }
            const double fh = std::sqrt(lo * hi);
            q.push_back(fp / (fh - fl));
        }
        table((std::string("k") + nm + "Q").c_str(), q);
    }

    // De-esser band-pass centre frequency versus frequency pot.
    {
        DkStage s(kDeesser);
        std::vector<double> v, g, ph;
        for (int i = 0; i < steps; ++i)
        {
            s.setParam(s.param("freq"), std::max(0.01, pos(i)));
            double pk;
            const double f = peakFreq(s, 300.0, 60000.0, &pk);
            v.push_back(f);
            g.push_back(pk);
            ph.push_back(std::arg(s.analogResponse(0, 0, f)));
        }
        table("kDeessFreqHz", v);
        table("kDeessBandDb", g);
        table("kDeessBandPhase", ph);
        for (double r : { 1.5, 2.0, 2.5, 5.0 })
        {
            s.setParam(s.param("freq"), r);
            double pk;
            std::printf("// de-esser pot %.0fk: %.1f Hz\n", 20 * r, peakFreq(s, 300.0, 60000.0, &pk));
        }
    }

    // Gain of each rotary position at 1 kHz (legends).
    {
        DkStage s(kMicInput);
        s.setParam(s.param("rsrc"), 0.0);
        s.setParam(s.param("zscale"), 1.0);
        std::vector<double> v;
        for (int k = 0; k < 12; ++k) { s.setParam(s.param("gain"), k); v.push_back(dbAt(s, 1000.0)); }
        table("kMicGainDb", v);
        DkStage l(kLineGain);
        v.clear();
        for (int k = 0; k < 7; ++k) { l.setParam(l.param("gain"), k); v.push_back(dbAt(l, 1000.0)); }
        table("kLineGainDb", v);
        DkStage li(kLineInput);
        std::printf("inline constexpr double kLineInputDb = %.6g;\n", dbAt(li, 1000.0));
        DkStage o(kOutput);
        const double og = 20.0 * std::log10(std::abs(o.analogResponse(0, 0, 1000.0) - o.analogResponse(1, 0, 1000.0)));
        std::printf("inline constexpr double kOutputDb = %.6g;\n", og);
    }
    std::printf("} // namespace bluechannel::model::calibration\n");
    return 0;
}
